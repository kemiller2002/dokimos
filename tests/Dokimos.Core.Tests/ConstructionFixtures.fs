      ExpectedOracleDigest = oracleDigest ()
      OracleRun = NotExecuted "not requested in this unit test"
      Host = None
      Claims = None
      ClaimedTests = []
      Authorization = ConstructionEvidence.emptyAuthorization }

let doorInputs () =
    { timerInputs () with
        SourceManifestJson = read "door-synthetic" "source-manifest.json"
        BlueprintJson = read "door-synthetic" "blueprint.json"
        PlanJson = read "door-synthetic" "plan.json"
        ExpectedPlanDigest = doorPlanDigest
        ManifestPath = "generated/Door/construction-manifest.json"
        Candidate = snapshot (generatedFiles "door-synthetic" "Door") (trailers doorPlanDigest "COH-DOOR" "DEC-DOOR")
        Base = Some { Commit = "base"; Entries = Map.empty; ProjectFiles = Map.empty }
        OracleBytes = None
        ExpectedOracleDigest = "" }

/// Replaces one committed file's bytes.
let withFile (path: string) (bytes: byte[]) (inputs: ConstructionInputs) =
    let files = inputs.Candidate.Contents |> Map.add path bytes |> Map.toList
    { inputs with Candidate = snapshot files inputs.Candidate.Message }

let withText path (text: string) inputs = withFile path (Encoding.UTF8.GetBytes text) inputs

let textOf (inputs: ConstructionInputs) path = Encoding.UTF8.GetString inputs.Candidate.Contents[path]

/// Rewrites one artifact and re-pins the manifest to its new bytes, so the
/// candidate is self-consistent: only an independent check can catch it.
let withSelfConsistentEdit (manifestPath: string) (path: string) (edit: string -> string) (inputs: ConstructionInputs) =
    let before = textOf inputs path
    let after = edit before
    if before = after then failwith "edit changed nothing"
    let oldDigest = ConstructionJson.sha256Text before
    let newDigest = ConstructionJson.sha256Text after
    let manifest = (textOf inputs manifestPath).Replace(oldDigest, newDigest)
    inputs |> withText path after |> withText manifestPath manifest

let verify inputs =
    match ConstructionVerification.verify inputs with
    | Ok report -> report
    | Error errors -> failwithf "verification refused: %A" errors

let codes (report: ConstructionVerificationReport) = report.Findings |> List.map _.Code

let subjects code (report: ConstructionVerificationReport) =
    report.Findings |> List.filter (fun f -> f.Code = code) |> List.map _.Subject
