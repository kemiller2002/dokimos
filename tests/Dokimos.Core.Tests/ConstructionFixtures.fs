/// In-memory construction candidates built from the pinned Ordo fixtures.
/// Each adversarial test derives its candidate from the valid one, so a test
/// can only fail for the one thing it changed.
module Dokimos.Core.Tests.ConstructionFixtures

open System
open System.IO
open System.Text
open Dokimos.Core

let repositoryRoot =
    let rec up (dir: DirectoryInfo) =
        if File.Exists(Path.Combine(dir.FullName, "Dokimos.sln")) then dir.FullName
        else
            match dir.Parent with
            | null -> failwith "Dokimos.sln not found"
            | parent -> up parent
    up (DirectoryInfo AppContext.BaseDirectory)

let fixture (name: string) (relative: string) =
    Path.Combine(repositoryRoot, "tests", "fixtures", "construction", name, relative)

let read name relative = File.ReadAllText(fixture name relative)

let timerPlanDigest = "sha256:860dd8fe579b4932207e77457373bb833180653f368376669090fdb5eb29fba8"
let doorPlanDigest = "sha256:9cb35aacff51e5e6f4e6398bd9cbb4e634f805cd5f60962f13d2c7a051011418"
let generator = "ordo.construction/1"
let oraclePath = Path.Combine(repositoryRoot, "oracles", "construction", "time-entry-timer", "oracle.json")
let oracleBytes () = File.ReadAllBytes oraclePath
let oracleDigest () = ConstructionJson.sha256Bytes (oracleBytes ())

let projectFile = """<Project Sdk="Microsoft.NET.Sdk"><ItemGroup><PackageReference Include="FSharp.Core" Version="8.0.0" /></ItemGroup></Project>"""

let trailers planDigest cohort decisions =
    String.concat "\n"
        [ "Construct generated/ from cohort " + cohort
          ""
          "Construction-Plan: " + planDigest
          "Construction-Generator: " + generator
          "Construction-Cohort: " + cohort
          "Construction-Decisions: " + decisions ]

let private entry (bytes: byte[]) = { Mode = "100644"; Blob = ConstructionJson.sha256Bytes bytes }

/// A candidate commit holding exactly the given files.
let snapshot (files: (string * byte[]) list) (message: string) =
    let contents = files |> Map.ofList
    { Commit = "c0ffee"
      CommittedAt = DateTimeOffset.UtcNow
      Message = message
      Entries = contents |> Map.map (fun _ bytes -> entry bytes)
      Contents = contents
      MarkerPaths =
        files |> List.filter (fun (_, b) -> (Encoding.UTF8.GetString b).StartsWith("// <auto-generated by ", StringComparison.Ordinal)) |> List.map fst
      ProjectFiles =
        files |> List.filter (fst >> ConstructionEvidence.isProjectFile) |> List.map (fun (p, b) -> p, Encoding.UTF8.GetString b) |> Map.ofList }

let generatedFiles name workflow =
    Directory.EnumerateFiles(fixture name (Path.Combine("generated", workflow)))
    |> Seq.sort
    |> Seq.map (fun p -> $"generated/{workflow}/{Path.GetFileName p}", File.ReadAllBytes p)
    |> Seq.toList

let baseSnapshot =
    { Commit = "base"
      Entries = Map.ofList [ "app/App.fsproj", entry (Encoding.UTF8.GetBytes projectFile) ]
      ProjectFiles = Map.ofList [ "app/App.fsproj", projectFile ] }

let timerFiles () = ("app/App.fsproj", Encoding.UTF8.GetBytes projectFile) :: generatedFiles "time-entry-timer" "Timer"

let timerInputs () =
    { CheckedAt = DateTimeOffset.UtcNow
      WorkItem = "GH-30"
