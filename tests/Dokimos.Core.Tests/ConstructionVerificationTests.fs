[<Fact>]
let ``generated transitions and manifest operations not in the plan are invented behavior`` () =
    let inputs =
        timerInputs ()
        |> withSelfConsistentEdit "generated/Timer/construction-manifest.json" "generated/Timer/Timer.Transition.g.fs"
            (fun code -> code.Replace("| TimerState.NoTimer, TimerCommand.Stop -> None", "| TimerState.NoTimer, TimerCommand.Stop -> Some TimerState.NoTimer"))
    let path = inputs.ManifestPath
    let manifest = (textOf inputs path).Replace("\"transition:Running/Stop\",", "\"transition:Running/Stop\", \"transition:NoTimer/Stop\",")
    let report = verify (withText path manifest inputs)
    let invented = subjects ConstructionCodes.InventedBehavior report
    Assert.Contains("transition:NoTimer/Stop", invented)
    Assert.Equal("nonconformant", report.StructuralStatus)

[<Fact>]
let ``a guard dropped from generated code or from the manifest is a missing required guard`` () =
    let door = doorInputs ()
    Assert.Empty (verify door).Findings
    let dropped =
        door |> withSelfConsistentEdit "generated/Door/construction-manifest.json" "generated/Door/Door.Transition.g.fs"
            (fun code -> code.Replace("| DoorState.Closed, DoorCommand.Lock -> [ DoorGuard.KeyPresent ]", "| DoorState.Closed, DoorCommand.Lock -> []"))
    Assert.Contains("KeyPresent@transition:Closed/Lock", subjects ConstructionCodes.MissingRequiredGuard (verify dropped))
    let bypassed =
        door |> withSelfConsistentEdit "generated/Door/construction-manifest.json" "generated/Door/Door.Transition.g.fs"
            (fun code -> code.Replace("guards state command", "([]: DoorGuard list)"))
    Assert.Contains("decide", subjects ConstructionCodes.MissingRequiredGuard (verify bypassed))
    let path = door.ManifestPath
    let noContract = (textOf door path).Replace("\"name\": \"DoorRules.Guard/KeyPresent\"", "\"name\": \"DoorRules.Note/KeyPresent\"")
    Assert.Contains("KeyPresent", subjects ConstructionCodes.MissingRequiredGuard (verify (withText path noContract door)))

