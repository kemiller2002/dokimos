[<Fact>]
let ``a self-consistent manifest still differs from the pinned generator output`` () =
    let reference = read "time-entry-timer" "generated/Timer/construction-manifest.json"
    let inputs =
        { timerInputs () with ReferenceManifestJson = Some reference }
        |> withSelfConsistentEdit "generated/Timer/construction-manifest.json" "generated/Timer/Timer.Transition.g.fs"
            (fun code -> code.Replace("Next = next;", "Next = state;"))
    let report = verify inputs
    Assert.Contains("generated/Timer/Timer.Transition.g.fs", subjects ConstructionCodes.GeneratedArtifactModified report)
    Assert.Contains("generated/Timer/construction-manifest.json", subjects ConstructionCodes.GeneratedArtifactModified report)

