[<Fact>]
let ``source excerpts are hashed against the pinned content digests`` () =
    let docs =
        IO.Directory.EnumerateFiles(fixture "time-entry-timer" "sources")
        |> Seq.map (fun p -> string (IO.Path.GetFileName p), IO.File.ReadAllBytes p) |> Map.ofSeq
    Assert.Empty (verify { timerInputs () with SourceDocuments = Some docs }).Findings
    let tampered = docs |> Map.add "timer-single-active.txt" (Encoding.UTF8.GetBytes "- Many timers may be active at a time.\n")
    let report = verify { timerInputs () with SourceDocuments = Some tampered }
    Assert.Contains("timer-single-active.txt", subjects ConstructionCodes.SourceContentMismatch report)
