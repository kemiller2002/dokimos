[<Fact>]
let ``changed plan digest is caught in the plan, the manifest, file headers and trailers`` () =
    let inputs = timerInputs ()
    let other = "sha256:" + String('0', 64)
    let report = verify { inputs with ExpectedPlanDigest = other }
    let found = subjects ConstructionCodes.PlanDigestChanged report
    for subject in [ "plan"; "construction-manifest"; "generated/Timer/Timer.Model.g.fs"; "Construction-Plan" ] do
        Assert.Contains(subject, found)
