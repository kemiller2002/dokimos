module Dokimos.Core.Tests.ConstructionVerificationTests

open System
open System.Text
open Xunit
open Dokimos.Core
open Dokimos.Core.Tests.ConstructionFixtures

let private planJson name = ConstructionJson.parse "plan" (read name "plan.json") |> Result.defaultWith failwith
let private blueprintJson name = ConstructionJson.parse "bp" (read name "blueprint.json") |> Result.defaultWith failwith

[<Fact>]
let ``independent canonical digests reproduce Ordo's pinned plan and blueprint digests`` () =
    Assert.Equal(timerPlanDigest, ConstructionCanonical.planDigest (planJson "time-entry-timer"))
    Assert.Equal(doorPlanDigest, ConstructionCanonical.planDigest (planJson "door-synthetic"))
    Assert.Equal("sha256:28dd3964f9c49f3492f3c34174ab04d57f4ddcba298276b2a287b4a6f3fdc4cb", ConstructionCanonical.blueprintDigest (blueprintJson "time-entry-timer"))
    Assert.Equal("sha256:3f01b259bc026a1806c6f26600db61a108c8508dcfe0f3b129f8002b88bb195f", ConstructionCanonical.blueprintDigest (blueprintJson "door-synthetic"))

[<Fact>]
let ``plan digest ignores operation order and name spelling but not meaning`` () =
    let text = read "time-entry-timer" "plan.json"
    let respelled = text.Replace("\"name\": \"No Timer\"", "\"name\": \"no-timer\"")
    Assert.Equal(timerPlanDigest, ConstructionCanonical.planDigest (ConstructionJson.parse "p" respelled |> Result.defaultWith failwith))
    let changed = text.Replace("\"to\": \"Paused\"", "\"to\": \"Running\"")
    Assert.NotEqual<string>(timerPlanDigest, ConstructionCanonical.planDigest (ConstructionJson.parse "p" changed |> Result.defaultWith failwith))

[<Fact>]
let ``valid construction without an observed oracle run is incomplete, never passed`` () =
    let report = verify (timerInputs ())
    Assert.Empty report.Findings
    Assert.Equal("incomplete", report.Verdict)
    Assert.Equal(3, report.ExitCode)
    Assert.Equal("unknown", report.BehaviorStatus)
    Assert.Equal("conformant", report.StructuralStatus)
    Assert.True report.GeneratorChecksConsistentWithPlan
    let counts = report.Counts
    Assert.Equal(7, counts.Imported)
    Assert.Equal(7, counts.Represented)
    Assert.Equal(6, counts.Modeled)
    Assert.Equal(6, counts.Generated)
    Assert.Equal(3, counts.Implemented)
    Assert.Equal(3, counts.ImplementedUnknown)
    Assert.Equal(0, counts.IndependentlyVerified)
    Assert.Equal(6, counts.VerificationUnknown)
    Assert.Equal(1, counts.Unresolved)
    Assert.Equal(0, counts.Deferred)
    Assert.Equal(0, counts.Waived)

