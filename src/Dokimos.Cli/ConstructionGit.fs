namespace Dokimos.Cli

open System
open System.Diagnostics
open System.IO
open System.Text
open Dokimos.Core

type ProcessOutcome = { ExitCode: int; Stdout: byte[]; Stderr: string }

/// Process and Git boundary for construction verification. Every candidate
/// file is read from Git objects at a resolved commit, never a working tree.
module ConstructionGit =
    /// Runs one process to completion. Failure to start is a value.
    let run (fileName: string) (args: string list) (workingDirectory: string option) (timeout: TimeSpan) =
        try
            let info = ProcessStartInfo(fileName, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false)
            args |> List.iter info.ArgumentList.Add
            workingDirectory |> Option.iter (fun d -> info.WorkingDirectory <- d)
            info.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] <- "1"
            info.Environment["DOTNET_NOLOGO"] <- "1"
            use proc =
                match Process.Start info with
                | null -> raise (InvalidOperationException(fileName + " did not start"))
                | started -> started
            use buffer = new MemoryStream()
            let copy = proc.StandardOutput.BaseStream.CopyToAsync buffer
            let stderr = proc.StandardError.ReadToEndAsync()
            if proc.WaitForExit(int timeout.TotalMilliseconds) then
                copy.Wait()
                Ok { ExitCode = proc.ExitCode; Stdout = buffer.ToArray(); Stderr = stderr.Result }
            else
                proc.Kill true
                Error(sprintf "%s timed out after %.0f seconds" fileName timeout.TotalSeconds)
        with
        | :? ComponentModel.Win32Exception as ex -> Error(fileName + " could not start: " + ex.Message)
        | :? InvalidOperationException as ex -> Error ex.Message

    let private git (repository: string) (args: string list) =
        match run "git" ("-C" :: repository :: args) None (TimeSpan.FromMinutes 2.0) with
        | Ok outcome when outcome.ExitCode = 0 -> Ok outcome.Stdout
        | Ok outcome -> Error(sprintf "git %s failed: %s" (String.concat " " args) (outcome.Stderr.Trim()))
        | Error reason -> Error reason

    let private text (bytes: byte[]) = Encoding.UTF8.GetString bytes

    let resolve repository (revision: string) =
        git repository [ "rev-parse"; "--verify"; "--quiet"; revision + "^{commit}" ] |> Result.map (text >> _.Trim())

    let tree repository commit =
        git repository [ "ls-tree"; "-r"; "-z"; "--full-tree"; commit ]
        |> Result.map (fun bytes ->
            (text bytes).Split('\000', StringSplitOptions.RemoveEmptyEntries)
            |> Array.choose (fun row ->
                match row.Split('\t', 2) with
                | [| meta; path |] ->
                    match meta.Split(' ') with
                    | [| mode; _; blob |] -> Some(path, { Mode = mode; Blob = blob })
                    | _ -> None
                | _ -> None)
            |> Map.ofArray)

    let blob repository (entry: TreeEntry) = git repository [ "cat-file"; "blob"; entry.Blob ]

    let private load repository (entries: Map<string, TreeEntry>) (paths: string list) =
        paths
        |> List.distinct
        |> List.choose (fun p -> Map.tryFind p entries |> Option.filter (fun e -> e.Mode.StartsWith "100") |> Option.map (fun e -> p, e))
        |> List.map (fun (p, e) -> blob repository e |> Result.map (fun bytes -> p, bytes))
        |> List.fold (fun acc item -> Result.bind (fun xs -> item |> Result.map (fun x -> x :: xs)) acc) (Ok [])
        |> Result.map Map.ofList

    let private markerPaths repository commit =
        match run "git" [ "-C"; repository; "grep"; "-l"; "-z"; "-F"; "// <auto-generated by "; commit; "--" ] None (TimeSpan.FromMinutes 2.0) with
        | Ok outcome when outcome.ExitCode = 0 ->
            Ok((text outcome.Stdout).Split('\000', StringSplitOptions.RemoveEmptyEntries)
               |> Array.map (fun hit -> if hit.StartsWith(commit + ":", StringComparison.Ordinal) then hit.Substring(commit.Length + 1) else hit)
               |> Array.toList)
        | Ok outcome when outcome.ExitCode = 1 -> Ok []
        | Ok outcome -> Error("git grep failed: " + outcome.Stderr.Trim())
        | Error reason -> Error reason

    let private projectFiles repository entries =
        entries |> Map.toList |> List.map fst |> List.filter ConstructionEvidence.isProjectFile
        |> load repository entries
        |> Result.map (Map.map (fun _ bytes -> text bytes))

    /// The candidate at one commit. The manifest is read first, so that the
    /// whole ownership root it names can be loaded from the same tree.
    let candidate repository commit (manifestPath: string) =
        tree repository commit
        |> Result.bind (fun entries ->
            let ownershipPaths =
                match Map.tryFind manifestPath entries |> Option.map (blob repository) with
                | Some(Ok bytes) ->
                    match ConstructionModels.readManifest (text bytes) with
                    | Ok m when m.OwnershipRoot <> "" && manifestPath.EndsWith(m.OwnershipRoot + "construction-manifest.json", StringComparison.Ordinal) ->
                        let mount = manifestPath.Substring(0, manifestPath.Length - (m.OwnershipRoot + "construction-manifest.json").Length)
                        let root = mount + m.OwnershipRoot
                        (entries |> Map.toList |> List.map fst |> List.filter (fun p -> p.StartsWith(root, StringComparison.Ordinal)))
                        @ (m.Artifacts |> List.map (fun a -> mount + a.Path))
                    | _ -> []
                | _ -> []
            let meta format = git repository [ "show"; "-s"; "--format=" + format; commit ] |> Result.map text
            match load repository entries (manifestPath :: ownershipPaths), markerPaths repository commit,
                  projectFiles repository entries, meta "%cI", meta "%B" with
            | Ok contents, Ok markers, Ok projects, Ok committed, Ok message ->
                match DateTimeOffset.TryParse(committed.Trim(), Globalization.CultureInfo.InvariantCulture, Globalization.DateTimeStyles.None) with
                | true, at ->
                    Ok { Commit = commit; CommittedAt = at; Message = message; Entries = entries; Contents = contents
                         MarkerPaths = markers; ProjectFiles = projects }
                | _ -> Error("unreadable commit time " + committed)
            | Error e, _, _, _, _ | _, Error e, _, _, _ | _, _, Error e, _, _ | _, _, _, Error e, _ | _, _, _, _, Error e -> Error e)

    let baseSnapshot repository commit =
        tree repository commit
        |> Result.bind (fun entries ->
            projectFiles repository entries |> Result.map (fun projects -> { Commit = commit; Entries = entries; ProjectFiles = projects }))
