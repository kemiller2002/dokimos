namespace Dokimos.Core

open System
open System.Text
open System.Text.RegularExpressions

/// One construction-verification finding. `Code` is the stable machine contract.
type ConstructionFinding =
    { Code: string
      Subject: string
      RequirementKeys: string list
      Detail: string }

/// Stable finding codes. Renaming one is a breaking contract change.
[<RequireQualifiedAccess>]
module ConstructionCodes =
    let GeneratedArtifactModified = "generated-artifact-modified"
    let GeneratedArtifactMissing = "generated-artifact-missing"
    let MissingRequiredGuard = "missing-required-guard"
    let FakeTestResult = "fake-test-result"
    let GeneratorVersionChanged = "generator-version-changed"
    let PlanDigestChanged = "plan-digest-changed"
    let UndocumentedGeneratedFile = "undocumented-generated-file"
    let HandwrittenClaimsGenerated = "handwritten-claims-generated"
    let RequirementSilentlyOmitted = "requirement-silently-omitted"
    let InventedBehavior = "invented-behavior"
    let UnauthorizedDependency = "unauthorized-dependency"
    let HostDenialWithoutEvidence = "host-denial-without-evidence"
    let CleanDiffNotDenial = "clean-diff-not-denial"
    let ProtectedWriteAllowed = "protected-write-allowed"
    let ConfinementClaimUnsupported = "confinement-claim-unsupported"
    let OracleBehaviorMismatch = "oracle-behavior-mismatch"
    let OracleDigestMismatch = "oracle-digest-mismatch"
    let OracleNotFrozen = "oracle-not-frozen-before-candidate"
    let OracleNotIndependent = "oracle-not-independent"
    let OracleSourceMismatch = "oracle-source-mismatch"
    let CandidateCompileFailed = "candidate-compile-failed"
    let BindingMismatch = "binding-mismatch"
    let ManifestPlanDivergence = "manifest-plan-divergence"
    let GeneratorSelfAttestation = "generator-self-attestation"
    let ManifestLocationMismatch = "manifest-location-mismatch"
    let ArtifactOutsideOwnershipRoot = "artifact-outside-ownership-root"
    let NonRegularGeneratedEntry = "non-regular-generated-entry"
    let ProvenanceTrailerMismatch = "provenance-trailer-mismatch"
    let SourceContentMismatch = "source-content-mismatch"
    let UnsupportedInput = "unsupported-input"

[<RequireQualifiedAccess>]
module ConstructionChecks =
    let finding code subject keys detail : ConstructionFinding =
        { Code = code; Subject = subject; RequirementKeys = keys; Detail = detail }

    let private when' condition code subject keys detail =
        if condition then [ finding code subject keys detail ] else []

    /// The generated-file marker `// <auto-generated by GEN from DIGEST>`.
    let marker (bytes: byte[]) =
        let text = Encoding.UTF8.GetString bytes
        let m = Regex.Match(text, @"^﻿?// <auto-generated by (\S+) from (\S+)>")
        if m.Success then Some(m.Groups[1].Value, m.Groups[2].Value) else None

    /// The pinned plan, generator and blueprint chain. Every digest is
    /// recomputed by Dokimos or compared with an independently pinned value.
    let binding (expectedPlan: string) (expectedGenerator: string) (sourceDigest: string) (blueprintDigest: string)
                (cohortNodes: string list) (plan: PlanModel) (manifest: ConstructionManifest) =
        let mismatch = ConstructionCodes.BindingMismatch
        let vocabularies = set [ DecisionModel.Vocabulary1; DecisionModel.Vocabulary2; DecisionModel.Vocabulary3 ]
        [ yield! when' (plan.SchemaVersion <> "ordo.construction-plan/1" || not (Set.contains plan.VocabularyVersion vocabularies))
                    ConstructionCodes.UnsupportedInput "plan" [] ("Unsupported plan schema " + plan.SchemaVersion + " / " + plan.VocabularyVersion)
          yield! when' (plan.RecomputedDigest <> expectedPlan) ConstructionCodes.PlanDigestChanged "plan" []
                    $"The supplied plan's canonical digest is {plan.RecomputedDigest}, not the pinned {expectedPlan}"
          yield! when' (manifest.PlanDigest <> expectedPlan) ConstructionCodes.PlanDigestChanged "construction-manifest" []
                    $"The candidate manifest names plan {manifest.PlanDigest}, not the pinned {expectedPlan}"
          yield! when' (manifest.GeneratorVersion <> expectedGenerator) ConstructionCodes.GeneratorVersionChanged "construction-manifest" []
                    $"The candidate manifest names generator {manifest.GeneratorVersion}, not the pinned {expectedGenerator}"
          yield! when' (plan.SourceManifestDigest <> sourceDigest) mismatch "plan.sourceManifestDigest" [] "The plan is bound to a different source manifest"
          yield! when' (plan.BlueprintDigest <> blueprintDigest) mismatch "plan.blueprintDigest" []
                    $"The plan is bound to blueprint {plan.BlueprintDigest}; the supplied blueprint recomputes to {blueprintDigest}"
          yield! when' (not (List.contains plan.CohortId cohortNodes)) mismatch "plan.cohortId" [] ("No cohort node " + plan.CohortId + " in the approved blueprint")
          for name, claimed, pinned in
              [ "manifest.binding.sourceManifestDigest", manifest.SourceManifestDigest, plan.SourceManifestDigest
                "manifest.binding.blueprintDigest", manifest.BlueprintDigest, plan.BlueprintDigest
                "manifest.binding.cohortId", manifest.CohortId, plan.CohortId
                "manifest.binding.decisionIds", String.concat "," manifest.DecisionIds, String.concat "," plan.DecisionIds ] do
              yield! when' (claimed <> pinned) mismatch name [] $"The candidate manifest says '{claimed}'; the pinned plan says '{pinned}'" ]

    /// Manifest claims re-derived from the pinned plan alone.
    let manifestAgainstPlan (plan: PlanModel) (assigned: Set<string>) (manifest: ConstructionManifest) =
        let claimedOps = manifest.Artifacts |> List.collect _.Operations |> Set.ofList
        let contractOps = manifest.ExtensionContracts |> List.collect _.Operations |> Set.ofList
        let covered = manifest.Artifacts |> List.collect _.RequirementKeys |> Set.ofList |> Set.union (Set.ofList manifest.CoveredKeys)
        let guards = ConstructionModels.requiredGuards plan
        let guardContracts = manifest.ExtensionContracts |> List.filter (fun c -> c.Kind = "guard-predicate")
        let obligationIds = manifest.Obligations |> List.map _.Id |> Set.ofList
        let pairs = manifest.StructuralPairs |> List.sort
        [ for op in Set.difference (Set.union claimedOps contractOps) (Set.union plan.Labels plan.OptionalLabels) do
              finding ConstructionCodes.InventedBehavior op [] "The manifest claims an operation that the pinned plan does not define"
          for op in Set.difference plan.Labels claimedOps do
              finding ConstructionCodes.ManifestPlanDivergence op [] "A plan operation is absent from every generated artifact"
          for key in Set.difference (manifest.Artifacts |> List.collect _.RequirementKeys |> Set.ofList) plan.TracedKeys do
              finding ConstructionCodes.InventedBehavior key [ key ] "An artifact traces to a requirement the plan never cites"
          for key in Set.difference assigned covered do
              finding ConstructionCodes.RequirementSilentlyOmitted key [ key ] "A cohort requirement is missing from the construction manifest"
          for guard, transitions in guards do
              let present =
                  guardContracts
                  |> List.tryFind (fun c -> c.Name.EndsWith("Guard/" + guard, StringComparison.Ordinal))
              match present with
              | None -> finding ConstructionCodes.MissingRequiredGuard guard [] ("The manifest declares no extension contract for plan guard " + guard)
              | Some c ->
                  for t in transitions do
                      if not (List.contains t c.Operations) then
                          finding ConstructionCodes.MissingRequiredGuard (guard + "@" + t) [] "The guard contract does not cover a guarded transition"
          for c in guardContracts do
              if not (guards |> List.exists (fun (g, _) -> c.Name.EndsWith("Guard/" + g, StringComparison.Ordinal))) then
                  finding ConstructionCodes.InventedBehavior c.Name [] "A guard contract the pinned plan does not require"
          for subject, keys in plan.Unresolved do
              if not (Set.contains ("RESOLVE:" + subject) obligationIds) then
                  finding ConstructionCodes.RequirementSilentlyOmitted ("RESOLVE:" + subject) keys "An unresolved plan question has no open obligation"
          if not (manifest.Obligations |> List.exists (fun o -> o.Kind = "verify-independently")) then
              finding ConstructionCodes.ManifestPlanDivergence "VERIFY" [] "The manifest drops the independent-verification obligation"
          if pairs <> (ConstructionModels.expectedPairs plan |> List.sort) then
              finding ConstructionCodes.ManifestPlanDivergence "structuralChecks" [] "The generator's structural checks disagree with the pinned plan"
          if manifest.StructuralIndependence <> "derived-from-plan" then
              finding ConstructionCodes.GeneratorSelfAttestation "structuralChecks" []
                  ("The generator labels its own checks '" + manifest.StructuralIndependence + "'; generator-derived checks are never independent") ]

    let private transitionArms (workflow: string) (code: string) =
        Regex.Matches(code, $@"(?m)^\s*\|\s*{workflow}State\.(\w+),\s*{workflow}Command\.(\w+)\s*->\s*Some\s+{workflow}State\.(\w+)\s*$")
        |> Seq.map (fun m -> m.Groups[1].Value, m.Groups[2].Value, m.Groups[3].Value)
        |> Set.ofSeq

    let private guardArms (workflow: string) (code: string) =
        Regex.Matches(code, $@"(?m)^\s*\|\s*{workflow}State\.(\w+),\s*{workflow}Command\.(\w+)\s*->\s*\[(.*)\]\s*$")
        |> Seq.map (fun m ->
            (m.Groups[1].Value, m.Groups[2].Value),
            Regex.Matches(m.Groups[3].Value, $@"{workflow}Guard\.(\w+)") |> Seq.map (fun g -> g.Groups[1].Value) |> Set.ofSeq)
        |> Map.ofSeq

    let private unionCases (typeName: string) (code: string) =
        let m = Regex.Match(code, $@"(?ms)^type {typeName} =\s*\n((?:\s*\|[^\n]*\n)+)")
        if not m.Success then None
        else Regex.Matches(m.Groups[1].Value, @"\|\s*(\w+)") |> Seq.map (fun c -> c.Groups[1].Value) |> Set.ofSeq |> Some

    /// Structural re-derivation over the candidate's committed generated
    /// code, in the published `ordo.construction/1` shape. This is code
    /// conformance, not behavioral acceptance.
    let generatedCode (plan: PlanModel) (transitionCode: string option) (modelCode: string option) =
        let w = plan.Workflow
        let planned = plan.Transitions |> List.map (fun t -> t.From, t.Command, t.To) |> Set.ofList
        [ match transitionCode with
          | None -> ()
          | Some code ->
              let arms = transitionArms w code
              for (f, c, t) in Set.difference arms planned do
                  finding ConstructionCodes.InventedBehavior $"transition:{f}/{c}" [] $"Generated code makes {f} --{c}--> {t} legal; the plan does not"
              for (f, c, t) in Set.difference planned arms do
                  finding ConstructionCodes.ManifestPlanDivergence $"transition:{f}/{c}" [] $"Generated code lacks the planned {f} --{c}--> {t}"
              let guards = guardArms w code
              let required = plan.Transitions |> List.filter (fun t -> not t.Guards.IsEmpty)
              if not required.IsEmpty && not (code.Contains "guards state command") then
                  finding ConstructionCodes.MissingRequiredGuard "decide" [] "decide never evaluates the guards the plan requires"
              for t in plan.Transitions do
                  let present = Map.tryFind (t.From, t.Command) guards |> Option.defaultValue Set.empty
                  for g in Set.difference (Set.ofList t.Guards) present do
                      finding ConstructionCodes.MissingRequiredGuard $"{g}@transition:{t.From}/{t.Command}" t.RequirementKeys "A plan guard is missing from the generated guards table"
                  for g in Set.difference present (Set.ofList t.Guards) do
                      finding ConstructionCodes.InventedBehavior $"{g}@transition:{t.From}/{t.Command}" [] "Generated code adds a guard the plan does not define"
          match modelCode with
          | None -> ()
          | Some code ->
              let commands = ConstructionModels.commands plan |> Set.ofList
              for typeName, expected in [ w + "State", Set.ofList plan.States; w + "Command", commands ] do
                  match unionCases typeName code with
                  | None -> finding ConstructionCodes.ManifestPlanDivergence typeName [] "The generated model does not declare this union"
                  | Some cases ->
                      for extra in Set.difference cases expected do
                          finding ConstructionCodes.InventedBehavior $"{typeName}.{extra}" [] "The generated model declares a case the plan does not define"
                      for missing in Set.difference expected cases do
                          finding ConstructionCodes.ManifestPlanDivergence $"{typeName}.{missing}" [] "The generated model omits a planned case" ]

    /// Praxis commit trailers are claims; each one present is checked.
    let trailers (expectedPlan: string) (expectedGenerator: string) (plan: PlanModel)
                 (sourceDigests: string list) (blueprintDigests: string list) (message: string) =
        let t = ConstructionEvidence.trailers message
        let check name ok code detail =
            match Map.tryFind name t with
            | Some value when not (ok value) -> [ finding code name [] (detail value) ]
            | _ -> []
        let digestOf (value: string) = value.Split(' ', StringSplitOptions.RemoveEmptyEntries) |> Array.tryLast |> Option.map ConstructionJson.normalizeDigest
        [ yield! check "Construction-Plan" (fun v -> ConstructionJson.normalizeDigest v = expectedPlan) ConstructionCodes.PlanDigestChanged
                    (fun v -> $"The commit claims plan {v}, not the pinned {expectedPlan}")
          yield! check "Construction-Generator" (fun v -> v = expectedGenerator) ConstructionCodes.GeneratorVersionChanged
                    (fun v -> $"The commit claims generator {v}, not the pinned {expectedGenerator}")
          yield! check "Construction-Cohort" (fun v -> v = plan.CohortId) ConstructionCodes.ProvenanceTrailerMismatch
                    (fun v -> $"The commit claims cohort {v}; the plan is bound to {plan.CohortId}")
          yield! check "Construction-Decisions"
                    (fun v -> (v.Split(' ', StringSplitOptions.RemoveEmptyEntries) |> Array.sort |> Array.toList) = plan.DecisionIds)
                    ConstructionCodes.ProvenanceTrailerMismatch (fun v -> $"The commit claims decisions '{v}'")
          yield! check "Construction-Manifest" (fun v -> digestOf v |> Option.exists (fun d -> List.contains d sourceDigests))
                    ConstructionCodes.ProvenanceTrailerMismatch (fun v -> $"The commit's source manifest claim '{v}' matches neither digest of the pinned manifest")
          yield! check "Construction-Blueprint" (fun v -> digestOf v |> Option.exists (fun d -> List.contains d blueprintDigests))
                    ConstructionCodes.ProvenanceTrailerMismatch (fun v -> $"The commit's blueprint claim '{v}' matches neither digest of the pinned blueprint") ]
