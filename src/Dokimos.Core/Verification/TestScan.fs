namespace Dokimos.Core.Verification

open System
open System.Text.RegularExpressions
open Dokimos.Core

/// One test found in source, before it is matched to a plan identity.
type ScannedTest =
    { File: string
      Line: int
      /// .NET: class/module full name; Playwright: the file relative to the test root.
      Container: string
      /// .NET: [method]; Playwright: describe titles then the test title.
      TitlePath: string list
      Skipped: bool
      Placeholder: bool
      Assertions: int
      TrivialAssertions: int
      /// Names (identifiers) the test body and its parameters reference.
      References: Set<string>
      /// File-local definitions and the names their bodies reference.
      LocalDefinitions: Map<string, Set<string>>
      /// File-local definitions whose own bodies assert.
      AssertingDefinitions: Set<string> }

/// Structural scanning of test sources. F# tests are found on the `SourceLexing` code view
/// (comments removed, literal contents blanked) using indentation scope; Playwright tests on a
/// JavaScript token view. This is syntax-aware but not a compiler: it does not resolve types or
/// macros, and a test generated by a helper function is not seen (reported as not generated).
module TestScan =
    let private identifiers (code: string) =
        Regex.Matches(code, @"``[^`]+``|[A-Za-z_][A-Za-z0-9_']*")
        |> Seq.map (fun m -> m.Value.Trim('`'))
        |> Set.ofSeq

    let private indentOf (line: string) = line.Length - line.TrimStart().Length

    /// A call to a helper whose name says it asserts (`assertNone`, `Check.check`, `verifyX`).
    /// A heuristic: a helper named so that does not assert is not detected.
    let private verbHelper =
        Regex(@"(?<![\w.])(?:[A-Za-z_]\w*\.)*(?:assert|check|verify|expect|ensure|should)\w*\s*[\(<\w""`\[]", RegexOptions.Compiled ||| RegexOptions.IgnoreCase)

    // ---------------------------------------------------------------- F#

    let private fsAssertion =
        Regex(@"\bAssert\.\w+|\bExpect\.\w+|\bshould\b|=!|\btest\s*<@|\bunquote\b|\bProp\.\w+|\braises\b", RegexOptions.Compiled)

    let private fsTrivial =
        Regex(
            @"\bAssert\.True\s*\(\s*true\s*[,)]|\bAssert\.False\s*\(\s*false\s*[,)]|\bAssert\.Equal\s*(<[^>]*>)?\s*\(\s*([\w.""]+)\s*,\s*\2\s*\)|\bAssert\.Pass\b|\bExpect\.isTrue\s+true\b|\btrue\s*=!\s*true\b|\bAssert\.NotNull\s*\(\s*""",
            RegexOptions.Compiled
        )

    let private fsPlaceholder =
        Regex(@"DOKIMOS-UNIMPLEMENTED|NotImplementedException|failwith\s+""(TODO|not implemented|stub)", RegexOptions.Compiled ||| RegexOptions.IgnoreCase)

    let private fsTestAttribute = Regex(@"\[<\s*(?:[\w]+\.)*(Fact|Theory|Property|Test|Tests)\b([^\]]*)>\]", RegexOptions.Compiled)
    let private fsLet = Regex(@"^\s*(\[<[^\]]*>\]\s*)*(let|member\s+\w+\.)\s*(rec\s+)?(``[^`]+``|[A-Za-z_][\w']*)", RegexOptions.Compiled)
    let private fsModule = Regex(@"^\s*module\s+((?:private|internal|public|rec)\s+)*([\w.]+)\s*(=)?", RegexOptions.Compiled)
    let private fsType = Regex(@"^\s*type\s+(?:(?:private|internal|public)\s+)?([\w]+)\s*\(", RegexOptions.Compiled)
    let private fsNamespace = Regex(@"^\s*namespace\s+(rec\s+)?([\w.]+)", RegexOptions.Compiled)
    let private fsLocalLet = Regex(@"^\s*let\s+(private\s+|inline\s+|rec\s+)*(``[^`]+``|[A-Za-z_][\w']*)", RegexOptions.Compiled)

    /// The lines of the block that starts at `start` (its first line plus every following line
    /// indented deeper than it; blank lines inside are kept).
    let private block (lines: LexedLine array) (start: int) =
        let indent = indentOf lines[start].Code
        let rest =
            lines
            |> Array.skip (start + 1)
            |> Array.takeWhile (fun l -> String.IsNullOrWhiteSpace l.Code || indentOf l.Code > indent)
        Array.append [| lines[start] |] rest

    let scanFSharp (file: string) (source: string) : ScannedTest list =
        let lines = SourceLexing.lex source |> Array.ofList

        // Enclosing container at each line: namespace + nested modules / class types by indentation.
        let containerAt =
            let folder (stack: (int * string) list, acc) (l: LexedLine) =
                if String.IsNullOrWhiteSpace l.Code then
                    stack, (match stack with [] -> "" | _ -> stack |> List.rev |> List.map snd |> String.concat ".") :: acc
                else
                    let indent = indentOf l.Code
                    let kept = stack |> List.filter (fun (i, _) -> i < indent)
                    let m = fsModule.Match l.Code
                    let t = fsType.Match l.Code
                    let n = fsNamespace.Match l.Code
                    let next =
                        // A namespace declaration starts a new scope; a file may hold several.
                        if n.Success then [ -2, n.Groups[2].Value ]
                        elif m.Success && m.Groups[3].Success then (indent, m.Groups[2].Value) :: kept
                        elif m.Success then [ -1, m.Groups[2].Value ]
                        elif t.Success then (indent, t.Groups[1].Value) :: kept
                        else kept
                    let name = next |> List.rev |> List.map snd |> String.concat "."
                    next, name :: acc
            lines |> Array.fold folder ([], []) |> snd |> List.rev |> Array.ofList

        let localDefinitions =
            lines
            |> Array.mapi (fun i l -> i, fsLocalLet.Match l.Code)
            |> Array.filter (fun (_, m) -> m.Success)
            |> Array.map (fun (i, m) ->
                let body = block lines i |> Array.map _.Code |> String.concat "\n"
                m.Groups[2].Value.Trim('`'), body)
            |> Array.filter (fun (name, _) -> name <> "")

        let assertingDefinitions =
            localDefinitions
            |> Array.filter (fun (_, body) -> fsAssertion.IsMatch body || verbHelper.IsMatch body || Regex.IsMatch(body, @"\bfailwithf?\b"))
            |> Array.map fst
            |> Set.ofArray

        let localDefinitions = localDefinitions |> Array.map (fun (n, b) -> n, identifiers b) |> Map.ofArray

        lines
        |> Array.mapi (fun i l -> i, l)
        |> Array.choose (fun (i, l) ->
            let attr = fsTestAttribute.Match l.Code
            if not attr.Success then None
            else
                // The declaration is on the attribute's line, or on the first code line after any
                // run of further attribute lines (e.g. many [<InlineData>]).
                let sameLine =
                    let m = fsLet.Match l.Code
                    m.Success && l.Code.IndexOf(attr.Value) < m.Groups[2].Index
                let declIndex =
                    if sameLine then Some i
                    else
                        [ i + 1 .. lines.Length - 1 ]
                        |> List.tryFind (fun k ->
                            let code = lines[k].Code.Trim()
                            code <> "" && not (code.StartsWith "[<" && code.EndsWith ">]"))
                        |> Option.filter (fun k -> fsLet.Match(lines[k].Code).Success)
                declIndex
                |> Option.map (fun k ->
                    let decl = fsLet.Match lines[k].Code
                    let body = block lines k
                    let code = body |> Array.map _.Code |> String.concat "\n"
                    let original = body |> Array.map _.Original |> String.concat "\n"
                    let attributes = [ i .. k ] |> List.map (fun j -> lines[j].Code) |> String.concat " "
                    let assertions =
                        fsAssertion.Matches(code).Count
                        + verbHelper.Matches(code).Count
                        + (if Regex.IsMatch(code, @"\bfailwithf?\b") && Regex.IsMatch(code, @"\bmatch\b|\bif\b") then 1 else 0)
                        + (if attr.Groups[1].Value.EndsWith "Property" && Regex.IsMatch(code, @"[=<>]|&&|\|\|") then 1 else 0)
                    { File = file
                      Line = lines[k].Number
                      Container = containerAt[k]
                      TitlePath = [ decl.Groups[4].Value.Trim('`') ]
                      Skipped = Regex.IsMatch(attributes, @"\bSkip\s*=") || Regex.IsMatch(code, @"\bSkip\.(If|Unless)\b|\bAssert\.Skip")
                      Placeholder = fsPlaceholder.IsMatch original
                      Assertions = assertions
                      TrivialAssertions = fsTrivial.Matches(code).Count
                      References = identifiers code
                      LocalDefinitions = localDefinitions
                      AssertingDefinitions = assertingDefinitions }))
        |> List.ofArray

    // ---------------------------------------------------------------- JavaScript

    let private matchingBrace (code: string) (openAt: int) =
        let rec go k depth =
            if k >= code.Length then code.Length
            elif code[k] = '{' then go (k + 1) (depth + 1)
            elif code[k] = '}' then (if depth = 1 then k else go (k + 1) (depth - 1))
            else go (k + 1) depth
        go openAt 0

    let private jsCall = Regex(@"\btest((?:\.(?:only|skip|fixme|fail|slow|describe|serial|parallel))*)\s*\(", RegexOptions.Compiled)
    let private jsAssertion = Regex(@"\bexpect(\.soft|\.poll)?\s*\(|\bassert(\.\w+)?\s*\(|\.toPass\s*\(", RegexOptions.Compiled)
    let private jsTrivial =
        Regex(@"\bexpect\s*\(\s*(true|false|null|\d+)\s*\)\s*\.\s*(toBe|toEqual|toStrictEqual)\s*\(\s*\1\s*\)|\bexpect\s*\(\s*true\s*\)\s*\.\s*toBeTruthy\s*\(\s*\)", RegexOptions.Compiled)
    let private jsPlaceholder = Regex(@"DOKIMOS-UNIMPLEMENTED|not implemented", RegexOptions.Compiled ||| RegexOptions.IgnoreCase)
    let private jsLocal = Regex(@"\b(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|\b(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\([^)]*\)|[A-Za-z_$][\w$]*)\s*=>", RegexOptions.Compiled)

    let private lineOf (text: string) (offset: int) =
        1 + (text.Substring(0, min offset text.Length) |> Seq.filter ((=) '\n') |> Seq.length)

    /// Playwright tests in one spec file. `file` is relative to the suite test root.
    let scanPlaywright (file: string) (source: string) : ScannedTest list =
        let view = JavaScriptLexing.lexJavaScript source
        let code = view.Code

        let calls =
            jsCall.Matches(code)
            |> Seq.choose (fun m ->
                let modifiers = m.Groups[1].Value
                // First argument must be a string literal.
                let rec firstNonSpace k = if k < code.Length && Char.IsWhiteSpace code[k] then firstNonSpace (k + 1) else k
                let argAt = firstNonSpace (m.Index + m.Length)
                match view.Literals |> Map.tryFind argAt with
                | None -> None
                | Some title ->
                    // The body follows the arrow (or a `function (...)` parameter list); a `{` before
                    // it is a destructured fixture parameter such as `async ({ page }) =>`.
                    let arrow = code.IndexOf("=>", argAt)
                    let nextCall = jsCall.Match(code, argAt)
                    let limit = if nextCall.Success then nextCall.Index else code.Length
                    let bodyOpen =
                        if arrow >= 0 && arrow < limit then code.IndexOf('{', arrow)
                        else
                            let fn = code.IndexOf("function", argAt)
                            if fn >= 0 && fn < limit then code.IndexOf('{', code.IndexOf(')', fn) |> max fn) else -1
                    if bodyOpen < 0 then None
                    else
                        let bodyClose = matchingBrace code bodyOpen
                        Some(m.Index, modifiers, title, argAt, bodyOpen, bodyClose))
            |> List.ofSeq

        let describes = calls |> List.filter (fun (_, mods, _, _, _, _) -> mods.Contains ".describe")

        let localDefinitions =
            jsLocal.Matches(code)
            |> Seq.map (fun m ->
                let name = if m.Groups[1].Success then m.Groups[1].Value else m.Groups[2].Value
                let openAt = code.IndexOf('{', m.Index)
                let body = if openAt < 0 then "" else code.Substring(openAt, matchingBrace code openAt - openAt + 1 |> min (code.Length - openAt))
                name, body)
            |> List.ofSeq

        let assertingDefinitions =
            localDefinitions |> List.filter (fun (_, body) -> jsAssertion.IsMatch body) |> List.map fst |> Set.ofList

        let localDefinitions = localDefinitions |> List.map (fun (n, b) -> n, identifiers b) |> Map.ofList

        calls
        |> List.filter (fun (_, mods, _, _, _, _) -> not (mods.Contains ".describe"))
        |> List.map (fun (start, mods, title, argAt, bodyOpen, bodyClose) ->
            let enclosing =
                describes
                |> List.filter (fun (s, _, _, _, o, c) -> s < start && o < start && c > start)
                |> List.sortBy (fun (s, _, _, _, _, _) -> s)
            let describeSkipped = enclosing |> List.exists (fun (_, m, _, _, _, _) -> m.Contains ".skip" || m.Contains ".fixme")
            let parameters = code.Substring(argAt, bodyOpen - argAt)
            let body = code.Substring(bodyOpen, min (bodyClose - bodyOpen + 1) (code.Length - bodyOpen))
            let originalBody = source.Substring(bodyOpen, min (bodyClose - bodyOpen + 1) (source.Length - bodyOpen))
            { File = file
              Line = lineOf source start
              Container = file
              TitlePath = (enclosing |> List.map (fun (_, _, t, _, _, _) -> t)) @ [ title ]
              Skipped = mods.Contains ".skip" || mods.Contains ".fixme" || describeSkipped || Regex.IsMatch(body, @"\btest\s*\.\s*(skip|fixme)\s*\(")
              Placeholder = jsPlaceholder.IsMatch originalBody
              Assertions = jsAssertion.Matches(body).Count
              TrivialAssertions = jsTrivial.Matches(body).Count
              References = identifiers (parameters + body)
              LocalDefinitions = localDefinitions
              AssertingDefinitions = assertingDefinitions })

    // ---------------------------------------------------------------- execution scope

    /// Files a .fsproj compiles (`<Compile Include>`, with simple globs), relative to its directory.
    let compiledFiles (fsproj: string) =
        Regex.Matches(fsproj, @"<Compile\s+Include\s*=\s*""([^""]+)""")
        |> Seq.map (fun m -> m.Groups[1].Value.Replace('\\', '/'))
        |> List.ofSeq

    let isCompiled (includes: string list) (relativeToProject: string) =
        includes |> List.exists (fun pattern -> pattern = relativeToProject || Glob.isMatch pattern relativeToProject)

    /// `dotnet test --filter` expressions over FullyQualifiedName: `|` separates alternatives,
    /// `&` conjunctions; `~` contains, `!~` does not contain, `=` equals, `!=` differs.
    let filterAdmits (filter: string option) (fullyQualifiedName: string) =
        match filter with
        | None -> true
        | Some expression ->
            expression.Trim('"').Split('|')
            |> Array.exists (fun alternative ->
                alternative.Split('&')
                |> Array.forall (fun term ->
                    let m = Regex.Match(term.Trim(), @"^FullyQualifiedName\s*(!~|~|!=|=)\s*(.+)$")
                    if not m.Success then true
                    else
                        let value = m.Groups[2].Value.Trim()
                        match m.Groups[1].Value with
                        | "~" -> fullyQualifiedName.Contains value
                        | "!~" -> not (fullyQualifiedName.Contains value)
                        | "=" -> fullyQualifiedName = value
                        | _ -> fullyQualifiedName <> value))

    let commandFilter (command: string) =
        let m = Regex.Match(command, @"--filter\s+(""[^""]*""|\S+)")
        if m.Success then Some(m.Groups[1].Value.Trim('"')) else None

    let commandProjects (command: string) =
        Regex.Matches(command, @"--project[= ](\S+)") |> Seq.map (fun m -> m.Groups[1].Value) |> List.ofSeq

    /// Names that reach one of the given symbols, directly or through file-local definitions.
    let rec reachesAny (targets: Set<string>) (test: ScannedTest) =
        let rec closure (known: Set<string>) =
            let grown =
                test.LocalDefinitions
                |> Map.filter (fun name refs -> not (known.Contains name) && not (Set.intersect refs known).IsEmpty)
                |> Map.keys
                |> Set.ofSeq
            if grown.IsEmpty then known else closure (Set.union known grown)
        not (Set.intersect (closure targets) test.References).IsEmpty

    /// The test asserts directly, or calls a file-local definition that (transitively) asserts.
    let asserts (test: ScannedTest) =
        test.Assertions > 0 || reachesAny test.AssertingDefinitions test

    /// Names that reach one of the boundary symbols, directly or through file-local definitions.
    let reaches (boundary: string list) (test: ScannedTest) =
        let rec closure (known: Set<string>) =
            let grown =
                test.LocalDefinitions
                |> Map.filter (fun name refs -> not (known.Contains name) && not (Set.intersect refs known).IsEmpty)
                |> Map.keys
                |> Set.ofSeq
            if grown.IsEmpty then known else closure (Set.union known grown)
        let reaching = closure (Set.ofList boundary)
        not (Set.intersect reaching test.References).IsEmpty
